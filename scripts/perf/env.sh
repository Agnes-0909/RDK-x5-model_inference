#!/usr/bin/env bash

set -euo pipefail

SOURCE_PATH="${BASH_SOURCE[0]}"
while [[ -L "${SOURCE_PATH}" ]]; do
  SOURCE_DIR="$(cd "$(dirname "${SOURCE_PATH}")" && pwd)"
  SOURCE_PATH="$(readlink "${SOURCE_PATH}")"
  [[ "${SOURCE_PATH}" != /* ]] && SOURCE_PATH="${SOURCE_DIR}/${SOURCE_PATH}"
done

SCRIPT_DIR="$(cd "$(dirname "${SOURCE_PATH}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
MT_ROOT="${PROJECT_ROOT}/multi_thread_proj"

export PROJECT_ROOT
export MT_ROOT

export BOARD_HOST="${BOARD_HOST:-root@192.168.1.12}"
export BOARD_BASE_DIR="${BOARD_BASE_DIR:-/root/multi_thread_proj}"
export BOARD_BIN_DIR="${BOARD_BIN_DIR:-${BOARD_BASE_DIR}/bin}"
export BOARD_LIB_DIR="${BOARD_LIB_DIR:-${BOARD_BASE_DIR}/lib}"
export BOARD_MODEL_DIR="${BOARD_MODEL_DIR:-${BOARD_BASE_DIR}/model}"
export BOARD_MODEL_PATH="${BOARD_MODEL_PATH:-${BOARD_MODEL_DIR}/model.bin}"
export BOARD_INPUT_BASE_DIR="${BOARD_INPUT_BASE_DIR:-${BOARD_BASE_DIR}/input}"
export BOARD_INPUT_DIR_0="${BOARD_INPUT_DIR_0:-${BOARD_INPUT_BASE_DIR}/channel0}"
export BOARD_INPUT_DIR_1="${BOARD_INPUT_DIR_1:-${BOARD_INPUT_BASE_DIR}/channel1}"
export BOARD_INPUT_DIR_2="${BOARD_INPUT_DIR_2:-${BOARD_INPUT_BASE_DIR}/channel2}"
export BOARD_LOG_DIR="${BOARD_LOG_DIR:-${BOARD_BASE_DIR}/log}"
export BOARD_UDS_PATH="${BOARD_UDS_PATH:-/tmp/mt_infer.sock}"
export BOARD_SHM_PATH="${BOARD_SHM_PATH:-/mt_infer_shm}"
export BOARD_BPU_CORE_PRIMARY="${BOARD_BPU_CORE_PRIMARY:-0}"
export BOARD_PASSWORD="${BOARD_PASSWORD:-root}"

export RUN_SECONDS="${RUN_SECONDS:-60}"

export SCP_BIN="${SCP_BIN:-scp}"
export SSH_BIN="${SSH_BIN:-ssh}"

export BUILD_SCRIPT_WRAPPER="${BUILD_SCRIPT_WRAPPER:-${PROJECT_ROOT}/perf/build.sh}"
export SERVER_BINARY_LOCAL="${SERVER_BINARY_LOCAL:-${MT_ROOT}/build_aarch64/mt_server}"
export MANAGER_BINARY_LOCAL="${MANAGER_BINARY_LOCAL:-${MT_ROOT}/build_aarch64/mt_manager}"
export SERVER_BINARY_REMOTE="${SERVER_BINARY_REMOTE:-${BOARD_BIN_DIR}/mt_server}"
export MANAGER_BINARY_REMOTE="${MANAGER_BINARY_REMOTE:-${BOARD_BIN_DIR}/mt_manager}"
export SERVER_PROCESS_NAME="${SERVER_PROCESS_NAME:-mt_server}"
export MANAGER_PROCESS_NAME="${MANAGER_PROCESS_NAME:-mt_manager}"
export REMOTE_SERVER_LOG="${REMOTE_SERVER_LOG:-${BOARD_LOG_DIR}/mt_server.log}"
export REMOTE_MANAGER_LOG="${REMOTE_MANAGER_LOG:-${BOARD_LOG_DIR}/mt_manager.log}"
export LOCAL_LOG_DIR="${LOCAL_LOG_DIR:-${PROJECT_ROOT}/skills_tmp_log}"

print_perf_env() {
  cat <<EOF
PROJECT_ROOT=${PROJECT_ROOT}
MT_ROOT=${MT_ROOT}
BOARD_HOST=${BOARD_HOST}
BOARD_BASE_DIR=${BOARD_BASE_DIR}
BOARD_BIN_DIR=${BOARD_BIN_DIR}
BOARD_LIB_DIR=${BOARD_LIB_DIR}
BOARD_MODEL_PATH=${BOARD_MODEL_PATH}
BOARD_INPUT_DIR_0=${BOARD_INPUT_DIR_0}
BOARD_INPUT_DIR_1=${BOARD_INPUT_DIR_1}
BOARD_INPUT_DIR_2=${BOARD_INPUT_DIR_2}
BOARD_LOG_DIR=${BOARD_LOG_DIR}
BOARD_UDS_PATH=${BOARD_UDS_PATH}
BOARD_SHM_PATH=${BOARD_SHM_PATH}
BOARD_BPU_CORE_PRIMARY=${BOARD_BPU_CORE_PRIMARY}
RUN_SECONDS=${RUN_SECONDS}
SERVER_BINARY_LOCAL=${SERVER_BINARY_LOCAL}
MANAGER_BINARY_LOCAL=${MANAGER_BINARY_LOCAL}
SERVER_BINARY_REMOTE=${SERVER_BINARY_REMOTE}
MANAGER_BINARY_REMOTE=${MANAGER_BINARY_REMOTE}
REMOTE_SERVER_LOG=${REMOTE_SERVER_LOG}
REMOTE_MANAGER_LOG=${REMOTE_MANAGER_LOG}
LOCAL_LOG_DIR=${LOCAL_LOG_DIR}
EOF
}
